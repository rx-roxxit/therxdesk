<?php

declare(strict_types=1);

namespace App\Console\Commands\RxDesk;

use Illuminate\Console\Command;
use Illuminate\Support\Arr;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Str;
use RuntimeException;

/**
 * Splits upstream's AGENTS.md into Claude Code rules, one file per section, so
 * a session loads only the rules of the files it works on instead of the whole
 * file at launch. Each section's globs come from `.claude/agent-rules.php`
 * (`true`: loaded at launch, a list of globs: loaded when Claude reads or edits
 * a matching file, `false`: left out). Upstream's `.ai/rules` files already
 * carry their own `paths:` and are copied as they are. Run it after every
 * upstream merge: it fails on a section the map does not name, so a new
 * upstream rule is never silently loaded at launch or dropped.
 */
class SplitAgentRules extends Command
{
    protected $signature = 'rxdesk:agent-rules
        {--check : Fail when the generated rules are out of date instead of writing them}
        {--base= : The folder holding AGENTS.md, .ai/rules and .claude (defaults to the project root)}';

    protected $description = 'Split AGENTS.md and .ai/rules into path-scoped Claude Code rules';

    private const string OUTPUT = '.claude/rules/upstream';

    private const string MAP = '.claude/agent-rules.php';

    private const string NOTICE = '<!-- Generated by `php artisan rxdesk:agent-rules`. Edit AGENTS.md, .ai/rules or .claude/agent-rules.php, never this file. -->';

    private string $base;

    public function handle(): int
    {
        $this->base = rtrim($this->option('base') ?: base_path(), '/');

        try {
            $expected = $this->expectedFiles();
        } catch (RuntimeException $exception) {
            $this->error($exception->getMessage());

            return self::FAILURE;
        }

        $existing = $this->existingFiles();

        if ($this->option('check')) {
            return $this->check($expected, $existing);
        }

        $this->write($expected, $existing);

        return self::SUCCESS;
    }

    /**
     * Every file the output folder should hold, keyed by its path inside it.
     *
     * @return array<string, string>
     */
    private function expectedFiles(): array
    {
        $map = $this->map();
        $sections = $this->sections(File::get("{$this->base}/AGENTS.md"));

        $mapFile = self::MAP;
        $unmapped = collect($sections)->diffKeys($map)->keys();

        if ($unmapped->isNotEmpty()) {
            throw new RuntimeException("AGENTS.md sections missing from {$mapFile}: {$unmapped->implode(', ')}");
        }

        $stale = collect($map)->diffKeys($sections)->keys();

        if ($stale->isNotEmpty()) {
            throw new RuntimeException("{$mapFile} names sections AGENTS.md no longer has: {$stale->implode(', ')}");
        }

        $files = [];

        foreach ($sections as $slug => $text) {
            $paths = $map[$slug];

            if ($paths === false) {
                continue;
            }

            $files["agents/{$slug}.md"] = $this->rule($paths, $text);
        }

        foreach (File::files("{$this->base}/.ai/rules") as $file) {
            if ($file->getExtension() !== 'md' || $file->getFilename() === 'index.md') {
                continue;
            }

            $source = File::get($file->getPathname());

            if (! preg_match('/\A---\n(?:.*\n)*?paths:/', $source)) {
                throw new RuntimeException(".ai/rules/{$file->getFilename()} has no paths: frontmatter, so it would load at launch.");
            }

            $files["ai/{$file->getFilename()}"] = $this->defuseImports($source);
        }

        ksort($files);

        return $files;
    }

    /**
     * @return array<string, true|false|list<string>>
     */
    private function map(): array
    {
        $path = "{$this->base}/".self::MAP;

        if (! File::exists($path)) {
            throw new RuntimeException(self::MAP.' is missing.');
        }

        $map = require $path;

        foreach ($map as $slug => $paths) {
            if (is_bool($paths)) {
                continue;
            }

            if (! is_array($paths) || blank($paths) || ! array_is_list($paths)) {
                throw new RuntimeException(self::MAP.": {$slug} must be true, false or a list of globs.");
            }
        }

        return $map;
    }

    /**
     * Splits AGENTS.md into its Laravel Boost blocks (`=== x rules ===`) and
     * its project sections (`## Heading`), keyed by slug.
     *
     * @return array<string, string>
     */
    private function sections(string $source): array
    {
        $boost = '';
        $project = $source;

        if (preg_match('/<laravel-boost-guidelines>\n(.*?)<\/laravel-boost-guidelines>\n?(.*)\z/s', $source, $matches)) {
            $boost = $matches[1];
            $project = $matches[2];
        }

        $sections = [];

        foreach ($this->split($boost, '/^=== (.+) rules ===$/', 'boost-') as $slug => $text) {
            $sections[$slug] = $text;
        }

        foreach ($this->split($project, '/^## (.+)$/', '') as $slug => $text) {
            if (array_key_exists($slug, $sections)) {
                throw new RuntimeException("Two AGENTS.md sections share the slug {$slug}.");
            }

            $sections[$slug] = $text;
        }

        return $sections;
    }

    /**
     * Cuts text at every line matching the heading pattern, outside fenced
     * code. A top-level `# ` heading only closes the current section; any
     * other text outside a section is refused, so nothing is lost.
     *
     * @return array<string, string>
     */
    private function split(string $text, string $heading, string $prefix): array
    {
        $sections = [];
        $slug = null;
        $inFence = false;

        foreach (explode("\n", $text) as $line) {
            if (str_starts_with($line, '```')) {
                $inFence = ! $inFence;
            }

            if (! $inFence && preg_match($heading, $line, $matches)) {
                $slug = $prefix.$this->slug($matches[1]);

                if (array_key_exists($slug, $sections)) {
                    throw new RuntimeException("Two AGENTS.md sections share the slug {$slug}.");
                }

                $sections[$slug] = "{$line}\n";

                continue;
            }

            if (! $inFence && $prefix === '' && preg_match('/^# /', $line)) {
                $slug = null;

                continue;
            }

            if ($slug === null) {
                if (filled($line)) {
                    throw new RuntimeException("AGENTS.md has text outside any section: {$line}");
                }

                continue;
            }

            $sections[$slug] .= "{$line}\n";
        }

        return Arr::map($sections, fn (string $section): string => rtrim($section)."\n");
    }

    private function slug(string $heading): string
    {
        return Str::slug(preg_replace('/[^\pL\pN]+/u', ' ', $heading));
    }

    /**
     * @param  true|list<string>  $paths
     */
    private function rule(bool|array $paths, string $text): string
    {
        $body = self::NOTICE."\n\n".$this->defuseImports($text);

        if ($paths === true) {
            return $body;
        }

        $globs = collect($paths)
            ->map(fn (string $glob): string => '  - "'.addcslashes($glob, '"\\').'"')
            ->implode("\n");

        return "---\npaths:\n{$globs}\n---\n\n{$body}";
    }

    /**
     * An `@path` naming a file of the project is a Claude Code import: it
     * would load that file in full wherever this rule loads. Wrap it in a code
     * span, which Claude Code never imports.
     */
    private function defuseImports(string $text): string
    {
        $inFence = false;
        $lines = explode("\n", $text);

        foreach ($lines as $index => $line) {
            if (str_starts_with($line, '```')) {
                $inFence = ! $inFence;

                continue;
            }

            if ($inFence) {
                continue;
            }

            $lines[$index] = preg_replace_callback(
                '/(?<![\w`])@([\w.\/~-]*[\w\/])/',
                fn (array $match): string => $this->isImport($line, $match[0][1], $match[1][0])
                    ? "`{$match[1][0]}`"
                    : $match[0][0],
                $line,
                flags: PREG_OFFSET_CAPTURE,
            );
        }

        return implode("\n", $lines);
    }

    private function isImport(string $line, int $offset, string $path): bool
    {
        if (substr_count(substr($line, 0, $offset), '`') % 2 === 1) {
            return false;
        }

        return File::isFile("{$this->base}/{$path}");
    }

    /**
     * @return array<string, string>
     */
    private function existingFiles(): array
    {
        $folder = "{$this->base}/".self::OUTPUT;

        if (! File::isDirectory($folder)) {
            return [];
        }

        $files = [];

        foreach (File::allFiles($folder) as $file) {
            $files[$file->getRelativePathname()] = $file->getContents();
        }

        return $files;
    }

    /**
     * @param  array<string, string>  $expected
     * @param  array<string, string>  $existing
     */
    private function check(array $expected, array $existing): int
    {
        $changed = [];

        foreach ($expected as $path => $contents) {
            if (! array_key_exists($path, $existing) || $existing[$path] !== $contents) {
                $changed[] = $path;
            }
        }

        $changed = collect($changed)->merge(collect($existing)->diffKeys($expected)->keys());

        if ($changed->isEmpty()) {
            $this->info('The agent rules are up to date.');

            return self::SUCCESS;
        }

        $this->error("The agent rules are out of date ({$changed->implode(', ')}). Run php artisan rxdesk:agent-rules.");

        return self::FAILURE;
    }

    /**
     * @param  array<string, string>  $expected
     * @param  array<string, string>  $existing
     */
    private function write(array $expected, array $existing): void
    {
        $folder = "{$this->base}/".self::OUTPUT;

        foreach (collect($existing)->diffKeys($expected)->keys() as $path) {
            File::delete("{$folder}/{$path}");
        }

        foreach ($expected as $path => $contents) {
            File::ensureDirectoryExists(dirname("{$folder}/{$path}"));
            File::put("{$folder}/{$path}", $contents);
        }

        $count = count($expected);

        $this->info("Wrote {$count} agent rule file(s).");
    }
}
